"""Run the scenario matrix and write a report.

    python -m sim.run                         # A-D x provider A/B x progressive/predictive
    python -m sim.run --minutes 15            # quicker
    python -m sim.run --scenario D --mode PREDICTIVE --provider A --explain 6
"""
from __future__ import annotations

import argparse
import csv
import time
from dataclasses import asdict
from pathlib import Path

from smartdialer.config import DialMode

from .engine import SimResult, Simulation
from .scenarios import BASE, matrix, scenario, sensitivity

ROOT = Path(__file__).resolve().parents[1]

HEADER = ("| scen | provider | mode | util | waiting | calls started | connected | abandoned "
          "| abandon % | connects/agent-h | dials/connect | safety decisions |")
RULE = "|" + "---|" * 12


def row(r: SimResult) -> str:
    acts = ", ".join(f"{k.replace('FALLBACK_PROGRESSIVE', 'FALLBACK')} {v}"
                     for k, v in sorted(r.actions.items(), key=lambda kv: -kv[1]))
    return (f"| {r.name} | {r.providers} | {r.mode.lower()} | {r.utilization:.0%} | "
            f"{r.waiting:.0%} | {r.calls_initiated} | {r.connected} | {r.abandoned} | "
            f"{r.abandon_rate:.2%} | {r.connects_per_agent_hour:.1f} | "
            f"{r.dials_per_connect:.1f} | {acts} |")


def write_timeseries(r: SimResult, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(asdict(r.samples[0]).keys()))
        writer.writeheader()
        for s in r.samples:
            writer.writerow(asdict(s))


def run_matrix(minutes: float, out_dir: Path) -> list[SimResult]:
    results = []
    for spec in matrix(minutes):
        t0 = time.time()
        r = Simulation(spec).run()
        results.append(r)
        write_timeseries(r, out_dir / f"timeseries_{r.name}_{r.providers}_{r.mode.lower()}.csv")
        print(row(r), f"  ({time.time() - t0:.1f}s)", flush=True)
        if r.invariant_violations:
            print("   INVARIANT VIOLATIONS:", r.invariant_violations)
    return results


def report(results: list[SimResult], sens: list[tuple[str, SimResult]], minutes: float) -> str:
    lines = [
        "# Simulation results",
        "",
        f"_Generated by `python -m sim.run --minutes {minutes:g}`. 50 agents, "
        f"{minutes:g} simulated minutes per run, wrap-up 6-14s, same random seed for every run._",
        "",
        "- **util**: share of logged-in agent time spent talking to a borrower.",
        "- **waiting**: share of logged-in time AVAILABLE, RESERVED or DIALING (not talking, "
        "not in wrap-up).",
        "- **abandoned**: borrower answered and no agent was connected (the compliance metric).",
        "- **safety decisions**: one per pacing tick (1s). REJECT here almost always means "
        "\"the pacer wanted more, but the in-flight ceiling is already reached\".",
        "",
        "Scenarios: " + "; ".join(f"**{k}** {v['description']}" for k, v in BASE.items()) + ".",
        "Provider A: fast and reliable. Provider B: 2-6s setup, 3% start timeouts, 2% rejects, "
        "15% duplicate webhooks, 0.2-3s webhook delay, 3% of webhooks 8-30s late (reordered).",
        "",
        HEADER, RULE,
    ]
    lines += [row(r) for r in results]
    lines += ["", "## Overflow tolerance sensitivity (scenario A, provider A, predictive)", "",
              "Abandon-rate circuit breaker disabled here, to show the raw trade-off the "
              "tolerance controls.", "",
              "| policy | util | waiting | connected | abandoned | abandon % |", "|---|---|---|---|---|---|"]
    lines += [f"| {label} | {r.utilization:.0%} | {r.waiting:.0%} | {r.connected} | "
              f"{r.abandoned} | {r.abandon_rate:.2%} |" for label, r in sens]
    lines += ["", "## Why did it decide that? (sample decisions, scenario D, provider A, predictive)", ""]
    d = next(r for r in results if r.name == "D" and r.providers == "A" and r.mode == "PREDICTIVE")
    for text in d.explained:
        lines += ["```", text, "```", ""]
    bad = [r for r in results if r.invariant_violations]
    lines += ["## Invariants", "",
              "All runs ended with every cross-table invariant holding "
              "(`smartdialer/invariants.py`)." if not bad else
              f"VIOLATIONS in {len(bad)} runs: " + "; ".join(str(r.invariant_violations) for r in bad)]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--minutes", type=float, default=60)
    ap.add_argument("--scenario", choices=list(BASE))
    ap.add_argument("--mode", choices=[m.value for m in DialMode], default="PREDICTIVE")
    ap.add_argument("--provider", choices=["A", "B"], default="A")
    ap.add_argument("--agents", type=int, default=50)
    ap.add_argument("--explain", type=int, default=0, help="print N sample decisions")
    ap.add_argument("--out", default=str(ROOT / "results"))
    args = ap.parse_args()
    out = Path(args.out)

    if args.scenario:
        spec = scenario(args.scenario, DialMode(args.mode), args.provider, args.minutes, args.agents)
        r = Simulation(spec).run()
        print(HEADER)
        print(RULE)
        print(row(r))
        print("failed:", r.failed, "cancelled:", r.cancelled)
        print("invariants:", r.invariant_violations or "OK")
        for text in r.explained[: args.explain]:
            print("\n" + text)
        write_timeseries(r, out / f"timeseries_{r.name}_{r.providers}_{r.mode.lower()}.csv")
        return

    print(HEADER)
    print(RULE)
    results = run_matrix(args.minutes, out)
    sens = []
    for label, spec in sensitivity(args.minutes):
        r = Simulation(spec).run()
        print(f"sensitivity {label}: util {r.utilization:.0%}, abandon {r.abandon_rate:.2%}")
        sens.append((label, r))
    text = report(results, sens, args.minutes)
    (ROOT / "docs" / "SIMULATION_RESULTS.md").write_text(text, encoding="utf-8")
    print(f"\nwrote docs/SIMULATION_RESULTS.md and {out}/timeseries_*.csv")


if __name__ == "__main__":
    main()
